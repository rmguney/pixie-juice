test('WebP is re-encoded within budget, and lossless mode leaves pixels alone', async ({ page }) => {
  const r = await page.evaluate(async () => {
    const api = window.pixieJuice!;
    const input = await window.testing.makeImage({ width: 256, height: 192, mime: 'image/webp', quality: 0.98 });
    const lossy = await api.optimize(input, { quality: 60 });
    const lossless = await api.optimize(input, { quality: 60, lossless: true });
    return {
      inputSize: input.length,
      lossySize: lossy.data.length,
      lossyFormat: lossy.format,
      lossyStats: await window.testing.compare(input, lossy.data),
      losslessStats: await window.testing.compare(input, lossless.data),
    };
  });
  expect(r.lossyFormat).toBe('webp');
  expect(r.lossySize).toBeLessThan(r.inputSize);
  expect(r.lossyStats.meanError).toBeLessThan(15.01);
  expect(r.losslessStats.meanError).toBe(0);
});

test('GIF, BMP, TGA, TIFF and ICO optimize to decodable files', async ({ page }) => {
  const results = await page.evaluate(async () => {
    const api = window.pixieJuice!;
    const png = await window.testing.makeImage({ width: 96, height: 64, mime: 'image/png', noise: 0 });
    const inputs: Record<string, Uint8Array> = {
      gif: (await api.convert(png, 'gif')).data,
      bmp: (await api.convert(png, 'bmp')).data,
      tga: (await api.convert(png, 'tga')).data,
      tiff: window.testing.uncompressedTiff(96, 64),
      ico: (await api.convert(png, 'ico')).data,
    };
    const out: Record<string, { format: string; inputSize: number; outputSize: number; meanError: number }> = {};
    for (const [name, input] of Object.entries(inputs)) {
      const result = await api.optimize(input, { quality: 90 });
      const stats = await window.testing.compare(input, result.data);
      out[name] = { format: result.format, inputSize: input.length, outputSize: result.data.length, meanError: stats.meanError };
    }
    return out;
  });
  expect(results.gif.format).toBe('gif');
  expect(results.bmp.format).toBe('png');
  expect(results.tga.format).toBe('png');
  expect(results.tiff.format).toBe('tiff');
  expect(results.tiff.outputSize).toBeLessThan(results.tiff.inputSize);
  expect(results.ico.format).toBe('ico');
  for (const [name, r] of Object.entries(results)) {
    expect(r.meanError, name).toBe(0);
    expect(r.outputSize, name).toBeLessThanOrEqual(r.inputSize);
  }
});

test('SVG is minified by SVGO and stays a valid SVG', async ({ page }) => {
  const r = await page.evaluate(async () => {
    const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by a drawing tool -->
<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100">
  <metadata>tool data</metadata>
  <g>
    <rect x="10.000000" y="10.000000" width="80.000000" height="80.000000" fill="#ff0000"/>
  </g>
</svg>`;
    const input = new TextEncoder().encode(svg);
    const out = await window.pixieJuice!.optimize(input);
    const text = new TextDecoder().decode(out.data);
    const parsed = new DOMParser().parseFromString(text, 'image/svg+xml');
    return {
      inputSize: input.length,
      outputSize: out.data.length,
      format: out.format,
      valid: !parsed.querySelector('parsererror') && parsed.documentElement.nodeName === 'svg',
      hasRect: text.includes('<rect') || text.includes('<path'),
      hasComment: text.includes('generated by'),
    };
  });
  expect(r.format).toBe('svg');
  expect(r.outputSize).toBeLessThan(r.inputSize);
  expect(r.valid).toBe(true);
  expect(r.hasRect).toBe(true);
  expect(r.hasComment).toBe(false);
});

test('SVG lossless mode only drops comments and metadata, never geometry', async ({ page }) => {
  const r = await page.evaluate(async () => {
    const svg = `<!-- comment --><svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10">
  <metadata>tool data</metadata>
  <path d="M 1.000000 1.000000 L 9.000000 9.000000"/>
  <g><rect x="2" y="2" width="3" height="3"/></g>
</svg>`;
    const out = await window.pixieJuice!.optimize(new TextEncoder().encode(svg), { lossless: true });
    return { changed: out.changed, text: new TextDecoder().decode(out.data) };
  });
  expect(r.changed).toBe(true);
  expect(r.text).toContain('d="M 1.000000 1.000000 L 9.000000 9.000000"');
  expect(r.text).toContain('<g><rect x="2" y="2" width="3" height="3"/></g>');
  expect(r.text).not.toContain('comment');
  expect(r.text).not.toContain('tool data');
});

test('SVG in a declared legacy encoding keeps its text', async ({ page }) => {
  const text = await page.evaluate(async () => {
    const svg = `<?xml version="1.0" encoding="ISO-8859-1"?>
<!-- padding that SVGO removes -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><text>Café</text></svg>`;
    // One byte per character, as a Latin-1 file has.
    const input = Uint8Array.from(svg, (c) => c.charCodeAt(0));
    const out = await window.pixieJuice!.optimize(input);
    return new TextDecoder().decode(out.data);
  });
  expect(text).toContain('<text>Café</text>');
});

test('converts to every target format', async ({ page }) => {
  const results = await page.evaluate(async () => {
    const api = window.pixieJuice!;
    const source = await window.testing.makeImage({ width: 300, height: 200, mime: 'image/png', alpha: true });
    const out: Record<string, { format: string; detected: string; width: number }> = {};
    for (const target of ['png', 'jpeg', 'webp', 'gif', 'bmp', 'tga', 'ico', 'tiff'] as const) {
      const result = await api.convert(source, target, { quality: 80 });
      const decoded = await window.testing.decode(result.data);
      out[target] = { format: result.format, detected: await api.detect(result.data), width: decoded.width };
    }
    return out;
  });
  for (const [target, r] of Object.entries(results)) {
    expect(r.format, target).toBe(target);
    expect(r.detected, target).toBe(`image:${target}`);
    expect(r.width, target).toBe(target === 'ico' ? 256 : 300);
  }
});
